package mentorship.roadmap.Java_Core.step2_Base.topic4_Loops.task1_WhileLoop;

public class WhileLoopDemo {
    public static void main(String[] args) {
        whileLoopDemo();
    }
    public static void whileLoopDemo() {
        int i = 1;
        while (i <= 1000) {
            System.out.println(i);
            i+=1;
        }
    }
}

package mentorship.roadmap.Java_Core.step2_Base.topic4_Loops.task4_ForLoopPrint;

public class ForLoopPrint {
    public static void main(String[] args) {
        forLoopPrint();
    }
    public static void forLoopPrint() {
        for (int i = 1; i <= 1000; i++) {
            System.out.println(i);
        }
    }
}

